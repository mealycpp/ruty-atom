"""Generator for the RUTY engine with M slice units per half-ring (2M slices per clock in 1600-bit mode).
usage: gen.py M [fixed]   fixed = '' (morphing), 'single' (1600 only), 'dual' (2x800 only)"""
import sys
import os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from keccak_ref import RHO64, round_constant
M = int(sys.argv[1]); FIX = sys.argv[2] if len(sys.argv) > 2 else ""
P = 32 // M; CW = max(1, (P).bit_length())
need = [(64 - RHO64[i % 5][i // 5]) % 64 for i in range(25)]
name = "ruty_core" if not FIX else f"keccak_{FIX}"
L = []; E = L.append
E(f"""// {name}: Keccak engine, {2*M} slices per clock. Generated by gen.py (M={M}). Flip-flops only, no memories.
// dual=0: ONE core, Keccak-p[1600], lane i = {{B_i, A_i}}; job control = core 0.
// dual=1: TWO job-independent cores, Keccak-p[800] each (core 0 = A halves, core 1 = B halves).
// Shared, free running: the slot counter. One slot = 1 rotate cycle + {P} pass cycles = {P+1} clocks.
//   rotate cycle : rho for every lane (fixed wiring) with the one-bit theta correction folded in
//   pass cycles  : pi, chi, iota of this round and theta of the next, {M} slices per half per clock
// A job = 1 opening slot (theta only) + one slot per round. Private per core: state, round counter, range, constant.
// A job starts on the next slot boundary. An idle core holds its lanes.
module {name}(input clk, input rst, input dual,
    input [1:0] wr, input wxor, input [4:0] widx, input [63:0] wdata,    // lane write (bit 0: A half, bit 1: B half)
    input [4:0] ridx, output reg [63:0] rdata,                           // lane read, one clock later
    input [1:0] start, input [4:0] first0, input [4:0] last0, input [4:0] first1, input [4:0] last1,
    output [1:0] busy);
  localparam IDLE = 2'd0, PRE = 2'd1, RUN = 2'd2;
  reg [31:0] A [0:24]; reg [31:0] B [0:24];
  reg [{CW-1}:0] cnt; reg [4:0] cpA, cpB; reg [31:0] rcA, rcB;
  reg [1:0] st0, st1, pend; reg th0, th1; reg [4:0] ri0, rl0, pf0, pl0, ri1, rl1, pf1, pl1;
  function [4:0] par(input [24:0] s); integer x; begin
    for (x = 0; x < 5; x = x + 1) par[x] = s[x] ^ s[x+5] ^ s[x+10] ^ s[x+15] ^ s[x+20]; end endfunction
  function [24:0] pc(input [24:0] a, input rcb, input pre); reg [24:0] b; integer x, y, i; begin
    for (x = 0; x < 5; x = x + 1) for (y = 0; y < 5; y = y + 1) b[y + 5*((2*x + 3*y) % 5)] = a[x + 5*y];
    for (i = 0; i < 25; i = i + 1) pc[i] = pre ? a[i] : (b[i] ^ (~b[(i%5+1)%5 + 5*(i/5)] & b[(i%5+2)%5 + 5*(i/5)]) ^ ((i == 0) & rcb)); end endfunction
  function [24:0] th(input [24:0] s, input [4:0] c, input [4:0] p, input en); integer i; begin
    for (i = 0; i < 25; i = i + 1) th[i] = s[i] ^ (en & (c[(i%5+4)%5] ^ p[(i%5+1)%5])); end endfunction
  function [63:0] rcf(input [4:0] r); case (r)""")
for ir in range(24): E(f"    5'd{ir}: rcf = 64'h{round_constant(ir, 64):016x};")
E("    default: rcf = 64'h0; endcase endfunction")
D = {"": "dual", "single": "1'b0", "dual": "1'b1"}[FIX]
E(f"""  wire du = {D};
  assign busy = {{(st1 != IDLE) | pend[1], (st0 != IDLE) | pend[0]}};
  wire [1:0] sA = st0, sB = du ? st1 : st0;
  wire thA = th0, thB = du ? th1 : th0;
  wire rot = (cnt == 0), last = (cnt == {P});
  wire rotA = rot & (sA == RUN), rotB = rot & (sB == RUN), pasA = ~rot & (sA != IDLE), pasB = ~rot & (sB != IDLE);
  wire [4:0] fxA = du ? cpA : cpB, fxB = du ? cpB : cpA;                 // theta correction for slice 0 of each half
  wire [63:0] rc0 = rcf(ri0), rc1 = rcf(ri1);
  // slice units
  wire [24:0] sl_A [0:{M-1}]; wire [24:0] sl_B [0:{M-1}]; wire [24:0] s_A [0:{M-1}]; wire [24:0] s_B [0:{M-1}];
  wire [4:0] c_A [0:{M-1}]; wire [4:0] c_B [0:{M-1}]; wire [24:0] o_A [0:{M-1}]; wire [24:0] o_B [0:{M-1}];
  wire [4:0] ciA = (cnt == 1) ? 5'd0 : cpA, ciB = (cnt == 1) ? 5'd0 : cpB;
  genvar g, j;
  generate for (j = 0; j < {M}; j = j + 1) begin : u
    for (g = 0; g < 25; g = g + 1) begin : t
      assign sl_A[j][g] = A[g][j]; assign sl_B[j][g] = B[g][j];
    end
    assign s_A[j] = pc(sl_A[j], rcA[j], sA == PRE); assign s_B[j] = pc(sl_B[j], rcB[j], sB == PRE);
    assign c_A[j] = par(s_A[j]);                    assign c_B[j] = par(s_B[j]);
    if (j == 0) begin : f
      assign o_A[j] = th(s_A[j], c_A[j], ciA, thA);        assign o_B[j] = th(s_B[j], c_B[j], ciB, thB);
    end else begin : n
      assign o_A[j] = th(s_A[j], c_A[j], c_A[j-1], thA);   assign o_B[j] = th(s_B[j], c_B[j], c_B[j-1], thB);
    end
  end endgenerate
  // lanes with the slice-0 correction applied, then rho as fixed wiring
  wire [31:0] fA [0:24]; wire [31:0] fB [0:24]; wire [31:0] rA [0:24]; wire [31:0] rB [0:24];
  wire [31:0] nA [0:24]; wire [31:0] nB [0:24];
  generate for (g = 0; g < 25; g = g + 1) begin : l
    assign fA[g] = {{A[g][31:1], A[g][0] ^ fxA[(g%5+1)%5]}};
    assign fB[g] = {{B[g][31:1], B[g][0] ^ fxB[(g%5+1)%5]}};
    for (j = 0; j < {M}; j = j + 1) begin : w
      assign nA[g][{32-M}+j] = o_A[j][g]; assign nB[g][{32-M}+j] = o_B[j][g];
    end""")
if M < 32: E(f"    assign nA[g][{31-M}:0] = A[g][31:{M}]; assign nB[g][{31-M}:0] = B[g][31:{M}];")
E("  end endgenerate")
for i in range(25):
    n = need[i]; n32 = n % 32
    rot64 = lambda v, n: v if n == 0 else f"{{{v}[{n-1}:0], {v}[63:{n}]}}"
    rot32 = lambda v, n: v if n == 0 else f"{{{v}[{n-1}:0], {v}[31:{n}]}}"
    E(f"  wire [63:0] x{i} = {{fB[{i}], fA[{i}]}}; wire [63:0] y{i} = {rot64(f'x{i}', n)};")
    E(f"  assign rA[{i}] = du ? {rot32(f'fA[{i}]', n32)} : y{i}[31:0]; assign rB[{i}] = du ? {rot32(f'fB[{i}]', n32)} : y{i}[63:32];")
E(f"""  integer k;
  always @(posedge clk) begin
    rdata <= {{B[ridx], A[ridx]}};
    if (rst) begin st0 <= IDLE; st1 <= IDLE; pend <= 2'b00; cnt <= 0; th0 <= 1'b0; th1 <= 1'b0; end
    else begin
      cnt <= last ? {CW}'d0 : cnt + {CW}'d1;                               // shared slot counter, free running
      if (start[0]) begin pend[0] <= 1'b1; pf0 <= first0; pl0 <= last0; end
      if (start[1] & du) begin pend[1] <= 1'b1; pf1 <= first1; pl1 <= last1; end
      if (last) begin                                                    // slot boundary: private job control
        case (st0)
          PRE: begin st0 <= RUN; ri0 <= pf0; rl0 <= pl0; th0 <= (pf0 != pl0); end
          RUN: if (ri0 != rl0) begin ri0 <= ri0 + 5'd1; th0 <= ((ri0 + 5'd1) != rl0); end
               else if (pend[0]) begin st0 <= PRE; th0 <= 1'b1; pend[0] <= start[0]; end
               else begin st0 <= IDLE; th0 <= 1'b0; end
          default: if (pend[0]) begin st0 <= PRE; th0 <= 1'b1; pend[0] <= start[0]; end
        endcase
        case (st1)
          PRE: begin st1 <= RUN; ri1 <= pf1; rl1 <= pl1; th1 <= (pf1 != pl1); end
          RUN: if (ri1 != rl1) begin ri1 <= ri1 + 5'd1; th1 <= ((ri1 + 5'd1) != rl1); end
               else if (pend[1]) begin st1 <= PRE; th1 <= 1'b1; pend[1] <= start[1] & du; end
               else begin st1 <= IDLE; th1 <= 1'b0; end
          default: if (pend[1]) begin st1 <= PRE; th1 <= 1'b1; pend[1] <= start[1] & du; end
        endcase
      end
      if (rot) begin rcA <= rc0[31:0]; rcB <= du ? rc1[31:0] : rc0[63:32]; end
      else begin rcA <= rcA >> {M % 32}; rcB <= rcB >> {M % 32}; cpA <= c_A[{M-1}]; cpB <= c_B[{M-1}]; end
      for (k = 0; k < 25; k = k + 1) begin
        if (wr[0] && widx == k) A[k] <= wxor ? (A[k] ^ wdata[31:0]) : wdata[31:0];
        else if (rotA) A[k] <= rA[k];
        else if (pasA) A[k] <= nA[k];
        if (wr[1] && widx == k) B[k] <= wxor ? (B[k] ^ wdata[63:32]) : wdata[63:32];
        else if (rotB) B[k] <= rB[k];
        else if (pasB) B[k] <= nB[k];
      end
    end
  end
endmodule""")
open(f"{name}_m{M}.v", "w").write("\n".join(L) + "\n")
