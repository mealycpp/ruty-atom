def perm(name, T, w):
    L = []
    L.append("static void %s(%s *A, int first, int last) {" % (name, T))
    L.append("  %s %s;" % (T, ", ".join("a%d = A[%d]" % (i, i) for i in range(25))))
    L.append("  %s %s; int r;" % (T, ", ".join(["b%d" % i for i in range(25)] + ["c%d" % i for i in range(5)] + ["d%d" % i for i in range(5)])))
    L.append("  for (r = first; r <= last; r++) {")
    for x in range(5): L.append("    c%d = a%d ^ a%d ^ a%d ^ a%d ^ a%d;" % (x, x, x + 5, x + 10, x + 15, x + 20))
    for x in range(5): L.append("    d%d = c%d ^ ROL%d(c%d, 1);" % (x, (x - 1) % 5, w, (x + 1) % 5))
    for x in range(5):
        for y in range(5):
            i = x + 5 * y; j = y + 5 * ((2 * x + 3 * y) % 5); n = RHO[i] % w
            L.append("    b%d = %s;" % (j, ("ROL%d(a%d ^ d%d, %d)" % (w, i, x, n)) if n else "(a%d ^ d%d)" % (i, x)))
    for i in range(25):
        y = i // 5; x = i % 5
        L.append("    a%d = b%d ^ (~b%d & b%d);" % (i, i, (x + 1) % 5 + 5 * y, (x + 2) % 5 + 5 * y))
    L.append("    a0 ^= (%s)RC[r];" % T)
    L.append("  }")
    L.append("  " + " ".join("A[%d] = a%d;" % (i, i) for i in range(25)))
    L.append("}")
    return "\n".join(L)
